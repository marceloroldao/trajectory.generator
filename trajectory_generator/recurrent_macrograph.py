"""Automatic recurrent-core extraction and reversible physical-path addressing.

This module closes the gap between an endogenous public universe graph and the
weighted streaming codec.

Given only a directed public transition graph it can:

1. find strongly connected components;
2. select the dominant recurrent component by asymptotic internal path growth;
3. detect entropy-bearing branch nodes;
4. collapse deterministic flights into a weighted information-clock macrograph;
5. build an exact physical-step codec directly on the recurrent core.

The physical codec uses every internal core transition with length 1. Therefore
it can represent trajectories that stop at *any* physical step, including in the
middle of a deterministic macro-flight. Deterministic flights do not create
extra trajectory multiplicity; their intermediate states are regenerated by the
public graph.

The macrograph remains useful as an information-clock interpretation, while the
physical codec is the endpoint-only operational layer for arbitrary physical
stopping times inside the recurrent core.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
from typing import Hashable, Mapping, Sequence

from .weighted_path_trajectory import WeightedEdge, WeightedPathCodec


Node = Hashable


def _stable_key(value: Node) -> str:
    return repr(value)


def normalize_graph(
    adjacency: Mapping[Node, Sequence[Node]],
) -> dict[Node, tuple[Node, ...]]:
    """Return a closed adjacency map containing target-only nodes as keys."""
    nodes = set(adjacency)
    for targets in adjacency.values():
        nodes.update(targets)
    return {
        node: tuple(adjacency.get(node, ()))
        for node in sorted(nodes, key=_stable_key)
    }


def strongly_connected_components(
    adjacency: Mapping[Node, Sequence[Node]],
) -> list[set[Node]]:
    """Tarjan SCC decomposition preserving edge multiplicity semantically."""
    edges = normalize_graph(adjacency)

    index = 0
    stack: list[Node] = []
    on_stack: set[Node] = set()
    indices: dict[Node, int] = {}
    low: dict[Node, int] = {}
    result: list[set[Node]] = []

    def visit(node: Node) -> None:
        nonlocal index
        indices[node] = low[node] = index
        index += 1
        stack.append(node)
        on_stack.add(node)

        for nxt in edges[node]:
            if nxt not in indices:
                visit(nxt)
                low[node] = min(low[node], low[nxt])
            elif nxt in on_stack:
                low[node] = min(low[node], indices[nxt])

        if low[node] == indices[node]:
            component: set[Node] = set()
            while True:
                item = stack.pop()
                on_stack.remove(item)
                component.add(item)
                if item == node:
                    break
            result.append(component)

    for node in edges:
        if node not in indices:
            visit(node)

    return result


def _is_recurrent_component(
    edges: Mapping[Node, Sequence[Node]],
    component: set[Node],
) -> bool:
    if len(component) > 1:
        return True
    node = next(iter(component))
    return any(nxt == node for nxt in edges[node])


def component_growth_rate(
    adjacency: Mapping[Node, Sequence[Node]],
    component: Sequence[Node] | set[Node],
    *,
    iterations: int = 4096,
) -> float:
    """Estimate the Perron growth factor from exact integer path counts.

    The nth-root estimate converges even for periodic irreducible components,
    where a plain normalized power iteration can oscillate.
    """
    if iterations < 1:
        raise ValueError("iterations must be >= 1")

    edges = normalize_graph(adjacency)
    comp = set(component)
    if not comp:
        return 0.0

    counts = {node: 1 for node in comp}
    initial_total = len(comp)

    for _ in range(iterations):
        nxt = {node: 0 for node in comp}
        for node, count in counts.items():
            if not count:
                continue
            for target in edges[node]:
                if target in comp:
                    nxt[target] += count
        counts = nxt
        if not any(counts.values()):
            return 0.0

    total = sum(counts.values())
    return math.exp(
        (math.log(total) - math.log(initial_total)) / iterations
    )


def dominant_recurrent_component(
    adjacency: Mapping[Node, Sequence[Node]],
) -> set[Node]:
    """Select the recurrent SCC with the largest internal path-growth rate."""
    edges = normalize_graph(adjacency)
    candidates = [
        component
        for component in strongly_connected_components(edges)
        if _is_recurrent_component(edges, component)
    ]
    if not candidates:
        raise ValueError("graph has no recurrent component")

    scored = [
        (
            component_growth_rate(edges, component),
            len(component),
            tuple(sorted((_stable_key(node) for node in component))),
            component,
        )
        for component in candidates
    ]
    scored.sort(key=lambda row: (row[0], row[1], row[2]), reverse=True)
    return set(scored[0][3])


def _internal_successors(
    edges: Mapping[Node, Sequence[Node]],
    component: set[Node],
    node: Node,
) -> list[Node]:
    return [target for target in edges[node] if target in component]


@dataclass(frozen=True)
class RecurrentStructure:
    component: tuple[Node, ...]
    branch_nodes: tuple[Node, ...]
    macro_edges: tuple[WeightedEdge, ...]
    physical_edges: tuple[WeightedEdge, ...]
    growth_rate: float


def _extract_macro_edges(
    edges: Mapping[Node, Sequence[Node]],
    component: set[Node],
) -> tuple[tuple[Node, ...], tuple[WeightedEdge, ...]]:
    """Collapse degree-1 internal flights between branch nodes.

    If the component is a fully deterministic cycle, a canonical anchor is used
    and the whole cycle becomes one zero-entropy macro-edge.
    """
    ordered_component = tuple(sorted(component, key=_stable_key))
    branches = tuple(
        node
        for node in ordered_component
        if len(_internal_successors(edges, component, node)) > 1
    )

    if not branches:
        anchor = ordered_component[0]
        path = [anchor]
        current = anchor
        seen = {anchor}

        while True:
            successors = _internal_successors(edges, component, current)
            if len(successors) != 1:
                raise ValueError(
                    "branch-free recurrent component is not deterministic"
                )
            current = successors[0]
            path.append(current)
            if current == anchor:
                break
            if current in seen:
                raise ValueError(
                    "deterministic recurrent walk did not return to anchor"
                )
            seen.add(current)

        edge = WeightedEdge(
            label=f"m0:{len(path) - 1}",
            source=anchor,
            target=anchor,
            length=len(path) - 1,
            path=tuple(path),
        )
        return (anchor,), (edge,)

    branch_set = set(branches)
    macro_edges: list[WeightedEdge] = []

    for source_index, source in enumerate(branches):
        successors = _internal_successors(edges, component, source)
        for outgoing_index, first in enumerate(successors):
            path = [source, first]
            current = first
            visited = {source}

            while current not in branch_set:
                if current in visited:
                    raise ValueError(
                        "deterministic cycle encountered before a branch node"
                    )
                visited.add(current)
                nxt = _internal_successors(edges, component, current)
                if len(nxt) != 1:
                    raise ValueError(
                        "non-branch core node does not have one internal successor"
                    )
                current = nxt[0]
                path.append(current)

            macro_edges.append(
                WeightedEdge(
                    label=(
                        f"m{source_index}.{outgoing_index}:"
                        f"{len(path) - 1}"
                    ),
                    source=source,
                    target=current,
                    length=len(path) - 1,
                    path=tuple(path),
                )
            )

    return branches, tuple(macro_edges)


def _extract_physical_edges(
    edges: Mapping[Node, Sequence[Node]],
    component: set[Node],
) -> tuple[WeightedEdge, ...]:
    ordered_component = tuple(sorted(component, key=_stable_key))
    index = {node: i for i, node in enumerate(ordered_component)}
    out: list[WeightedEdge] = []

    for source in ordered_component:
        internal = _internal_successors(edges, component, source)
        for outgoing_index, target in enumerate(internal):
            out.append(
                WeightedEdge(
                    label=f"p{index[source]}.{outgoing_index}",
                    source=source,
                    target=target,
                    length=1,
                    path=(source, target),
                )
            )

    return tuple(out)


def derive_recurrent_structure(
    adjacency: Mapping[Node, Sequence[Node]],
) -> RecurrentStructure:
    edges = normalize_graph(adjacency)
    component = dominant_recurrent_component(edges)
    branch_nodes, macro_edges = _extract_macro_edges(edges, component)
    physical_edges = _extract_physical_edges(edges, component)

    return RecurrentStructure(
        component=tuple(sorted(component, key=_stable_key)),
        branch_nodes=branch_nodes,
        macro_edges=macro_edges,
        physical_edges=physical_edges,
        growth_rate=component_growth_rate(edges, component),
    )


def build_physical_core_codec(
    adjacency: Mapping[Node, Sequence[Node]],
    *,
    width: int | None = 63,
    start_nodes: Sequence[Node] | None = None,
) -> tuple[RecurrentStructure, WeightedPathCodec]:
    """Build a codec valid at every physical step inside the dominant core.

    By default every node in the recurrent component is an admissible initial
    core state, so the initial core state is encoded in the address rather than
    supplied as side metadata.
    """
    structure = derive_recurrent_structure(adjacency)

    starts = (
        structure.component
        if start_nodes is None
        else tuple(start_nodes)
    )

    codec = WeightedPathCodec(
        structure.component,
        structure.physical_edges,
        start_nodes=starts,
        width=width,
    )
    return structure, codec


def build_information_clock_codec(
    adjacency: Mapping[Node, Sequence[Node]],
    *,
    width: int | None = 63,
) -> tuple[RecurrentStructure, WeightedPathCodec]:
    """Build the branch-aligned macro-event codec.

    This representation is useful for information-clock analysis but only
    represents prefixes ending on macrograph branch nodes. Use
    build_physical_core_codec() when arbitrary physical stopping times matter.
    """
    structure = derive_recurrent_structure(adjacency)
    codec = WeightedPathCodec(
        structure.branch_nodes,
        structure.macro_edges,
        start_nodes=structure.branch_nodes,
        width=width,
    )
    return structure, codec


def monotone_physical_frontier(
    codec: WeightedPathCodec,
) -> int:
    """Largest consecutive physical horizon that fits the configured width."""
    if codec.width is None:
        raise ValueError("frontier requires a finite codec width")

    t = 0
    while codec.capacity_ok(t + 1):
        t += 1
    return t
