"""Streaming public-graph path codec backed by a fixed recurrence count field.

The address semantics are identical to WeightedPathCodec/PublicGraphTrajectory.
Only the public count-field implementation changes:

old reference:
    cache every D(v,t) row reached -> O(V*T) integers

this codec:
    minimal Krylov basis + recurrence -> O(V*d) integers
    plus a bounded small row cache

where d <= V is the minimal vector-recurrence order generated by the public
initial count vector.
"""

from __future__ import annotations

from typing import Hashable, Mapping, Sequence

from .count_field_recurrence import CountFieldRecurrence
from .weighted_path_trajectory import WeightedEdge, WeightedPathCodec


Node = Hashable


def _stable_key(value: Node) -> str:
    return repr(value)


class RecurrencePathCodec(WeightedPathCodec):
    def __init__(
        self,
        nodes: Sequence[Node],
        edges: Sequence[WeightedEdge],
        *,
        start_nodes: Sequence[Node],
        width: int | None,
        count_field: CountFieldRecurrence,
    ) -> None:
        super().__init__(
            nodes,
            edges,
            start_nodes=start_nodes,
            width=width,
        )
        self.count_field = count_field

    def _ensure_counts(self, physical_steps: int) -> None:
        # Intentionally no growing DP table.
        if physical_steps < 0:
            return

    def count_node(self, node: Node, physical_steps: int) -> int:
        if physical_steps < 0:
            return 0
        if node not in self.node_set:
            raise KeyError(node)
        return self.count_field.count(node, physical_steps)

    def total_count(self, physical_steps: int) -> int:
        if physical_steps < 0:
            raise ValueError("physical_steps must be >= 0")
        return self.count_field.total(physical_steps)


def build_recurrence_path_codec(
    adjacency: Mapping[Node, Sequence[Node]],
    *,
    start_nodes: Sequence[Node],
    width: int | None = 63,
    cache_rows: int = 4,
) -> RecurrencePathCodec:
    field = CountFieldRecurrence(
        adjacency,
        start_nodes=start_nodes,
        cache_rows=cache_rows,
    )

    nodes = field.nodes
    node_index = {
        node: i
        for i, node in enumerate(nodes)
    }

    edges: list[WeightedEdge] = []
    for source in nodes:
        for outgoing_index, target in enumerate(
            adjacency.get(source, ())
        ):
            if target not in node_index:
                raise AssertionError(
                    "reachable subgraph is not forward-closed"
                )
            edges.append(
                WeightedEdge(
                    label=f"r{node_index[source]}.{outgoing_index}",
                    source=source,
                    target=target,
                    length=1,
                    path=(source, target),
                )
            )

    return RecurrencePathCodec(
        nodes,
        edges,
        start_nodes=tuple(start_nodes),
        width=width,
        count_field=field,
    )
