"""Exact fixed-memory recurrence oracle for public graph path counts.

For a finite public graph with reachable-node count V and public initial count
vector D_0, the endpoint-count field evolves linearly:

    D_(t+1) = A^T D_t

where A is the public adjacency matrix under the row-source convention used by
this module.

The Krylov sequence

    D_0, D_1, D_2, ...

must therefore satisfy an exact vector recurrence of order d <= V:

    D_(n+d) = sum(c_i * D_(n+i), i=0..d-1).

This module derives the *minimal recurrence for the specific public initial
vector* by exact rational elimination. In the topological universes currently
used by trajectory.generator, the resulting coefficients are integers.

Once the recurrence is frozen, any count row D_t is regenerated by computing

    x^t mod m(x)

where

    m(x) = x^d - sum(c_i x^i).

The result is a linear combination of only the first d count vectors. Storage
is therefore O(V*d), independent of the requested horizon T, plus an optional
small bounded LRU row cache.

This is public-law state, not trajectory-specific history.
"""

from __future__ import annotations

from collections import OrderedDict
from fractions import Fraction
from typing import Hashable, Mapping, Sequence


Node = Hashable


def _stable_key(value: Node) -> str:
    return repr(value)


def reachable_nodes(
    adjacency: Mapping[Node, Sequence[Node]],
    start_nodes: Sequence[Node],
) -> tuple[Node, ...]:
    starts = tuple(start_nodes)
    if not starts:
        raise ValueError("start_nodes must be non-empty")

    all_nodes = set(adjacency)
    for targets in adjacency.values():
        all_nodes.update(targets)

    unknown = set(starts) - all_nodes
    if unknown:
        raise ValueError(f"start node outside graph: {unknown!r}")

    seen = set(starts)
    stack = list(starts)
    while stack:
        source = stack.pop()
        for target in adjacency.get(source, ()):
            if target not in seen:
                seen.add(target)
                stack.append(target)

    return tuple(sorted(seen, key=_stable_key))


def _step_vector(
    outgoing: Sequence[Sequence[int]],
    vector: Sequence[int],
) -> tuple[int, ...]:
    out = [0] * len(vector)
    for source, count in enumerate(vector):
        if not count:
            continue
        for target in outgoing[source]:
            out[target] += count
    return tuple(out)


def _derive_minimal_vector_recurrence(
    outgoing: Sequence[Sequence[int]],
    initial: Sequence[int],
) -> tuple[tuple[int, ...], tuple[tuple[int, ...], ...]]:
    """Return integer recurrence coefficients and the fixed Krylov basis.

    Exact Gaussian elimination is performed incrementally over Q. The first
    dependency is the minimal recurrence for this Krylov sequence.
    """
    dimension = len(initial)
    if dimension == 0:
        raise ValueError("count field must contain at least one node")

    basis: dict[
        int,
        tuple[list[Fraction], list[Fraction]],
    ] = {}

    sequence: list[tuple[int, ...]] = [tuple(int(x) for x in initial)]

    for degree in range(dimension + 1):
        if degree >= len(sequence):
            sequence.append(_step_vector(outgoing, sequence[-1]))

        vector = sequence[degree]
        residual = [Fraction(value) for value in vector]

        # residual = vector - sum(coeff_i * sequence[i])
        coeff = [Fraction(0) for _ in range(degree)]

        for pivot in sorted(basis):
            basis_vector, representation = basis[pivot]
            factor = residual[pivot]
            if not factor:
                continue

            for row in range(dimension):
                residual[row] -= factor * basis_vector[row]
            for i, value in enumerate(representation):
                coeff[i] += factor * value

        pivot = next(
            (i for i, value in enumerate(residual) if value),
            None,
        )

        if pivot is None:
            if degree == 0:
                raise ValueError("zero initial count vector")

            integer_coefficients = []
            for value in coeff:
                if value.denominator != 1:
                    raise ValueError(
                        "minimal recurrence has non-integer coefficient"
                    )
                integer_coefficients.append(int(value))

            return (
                tuple(integer_coefficients),
                tuple(sequence[:degree]),
            )

        if degree == dimension:
            break

        scale = residual[pivot]
        normalized = [value / scale for value in residual]

        # normalized = (sequence[degree] - sum(coeff_i*sequence[i]))/scale
        representation = [
            -value / scale
            for value in coeff
        ] + [Fraction(1, 1) / scale]

        basis[pivot] = (normalized, representation)

    raise AssertionError(
        "Krylov recurrence order exceeded reachable state dimension"
    )


def _poly_multiply_mod(
    left: Sequence[int],
    right: Sequence[int],
    recurrence: Sequence[int],
) -> list[int]:
    order = len(recurrence)
    work = [0] * (2 * order - 1)

    for i, a in enumerate(left):
        if not a:
            continue
        for j, b in enumerate(right):
            if b:
                work[i + j] += a * b

    # x^order = sum(recurrence[i] * x^i)
    for degree in range(2 * order - 2, order - 1, -1):
        value = work[degree]
        if not value:
            continue
        for i, coefficient in enumerate(recurrence):
            if coefficient:
                work[degree - order + i] += value * coefficient

    return work[:order]


def _nth_recurrence_weights(
    n: int,
    recurrence: Sequence[int],
) -> tuple[int, ...]:
    if n < 0:
        raise ValueError("n must be >= 0")

    order = len(recurrence)
    if order < 1:
        raise ValueError("recurrence must be non-empty")

    if n < order:
        out = [0] * order
        out[n] = 1
        return tuple(out)

    result = [1] + [0] * (order - 1)

    # Polynomial representing x modulo m(x).
    if order == 1:
        power = [recurrence[0]]
    else:
        power = [0] * order
        power[1] = 1

    exponent = n
    while exponent:
        if exponent & 1:
            result = _poly_multiply_mod(
                result,
                power,
                recurrence,
            )
        exponent >>= 1
        if exponent:
            power = _poly_multiply_mod(
                power,
                power,
                recurrence,
            )

    return tuple(result)


class CountFieldRecurrence:
    """Exact bounded-memory endpoint-count oracle for a public graph."""

    def __init__(
        self,
        adjacency: Mapping[Node, Sequence[Node]],
        *,
        start_nodes: Sequence[Node],
        cache_rows: int = 4,
    ) -> None:
        if cache_rows < 0:
            raise ValueError("cache_rows must be >= 0")

        self.start_nodes = tuple(start_nodes)
        self.nodes = reachable_nodes(adjacency, self.start_nodes)
        self.node_index = {
            node: i
            for i, node in enumerate(self.nodes)
        }

        self.outgoing = tuple(
            tuple(
                self.node_index[target]
                for target in adjacency.get(source, ())
            )
            for source in self.nodes
        )

        initial = [0] * len(self.nodes)
        for node in self.start_nodes:
            initial[self.node_index[node]] += 1
        self.initial_vector = tuple(initial)

        (
            self.coefficients,
            self.basis_vectors,
        ) = _derive_minimal_vector_recurrence(
            self.outgoing,
            self.initial_vector,
        )

        self.order = len(self.coefficients)
        self.cache_rows = cache_rows
        self._cache: OrderedDict[int, tuple[int, ...]] = OrderedDict()

        first_nonzero = next(
            (
                i
                for i, value in enumerate(self.coefficients)
                if value
            ),
            self.order,
        )
        self.transient_factor_power = first_nonzero
        self.reduced_coefficients = self.coefficients[first_nonzero:]

    @property
    def reachable_state_count(self) -> int:
        return len(self.nodes)

    @property
    def basis_integer_count(self) -> int:
        return self.reachable_state_count * self.order

    @property
    def cached_row_count(self) -> int:
        return len(self._cache)

    def direct_table_integer_count(self, horizon: int) -> int:
        if horizon < 0:
            raise ValueError("horizon must be >= 0")
        return self.reachable_state_count * (horizon + 1)

    def _remember(
        self,
        t: int,
        vector: tuple[int, ...],
    ) -> tuple[int, ...]:
        if self.cache_rows == 0:
            return vector

        self._cache[t] = vector
        self._cache.move_to_end(t)

        while len(self._cache) > self.cache_rows:
            self._cache.popitem(last=False)

        return vector

    def vector_at(self, t: int) -> tuple[int, ...]:
        if t < 0:
            raise ValueError("t must be >= 0")

        cached = self._cache.get(t)
        if cached is not None:
            self._cache.move_to_end(t)
            return cached

        if t < self.order:
            vector = self.basis_vectors[t]
            return self._remember(t, vector)

        weights = _nth_recurrence_weights(
            t,
            self.coefficients,
        )

        out = [0] * self.reachable_state_count
        for i, weight in enumerate(weights):
            if not weight:
                continue
            basis = self.basis_vectors[i]
            for j, value in enumerate(basis):
                if value:
                    out[j] += weight * value

        if any(value < 0 for value in out):
            raise AssertionError("count recurrence produced negative count")

        return self._remember(t, tuple(out))

    def step_vector(
        self,
        vector: Sequence[int],
    ) -> tuple[int, ...]:
        if len(vector) != self.reachable_state_count:
            raise ValueError("count vector has wrong dimension")
        return _step_vector(self.outgoing, vector)

    def count(self, node: Node, t: int) -> int:
        index = self.node_index.get(node)
        if index is None:
            return 0
        return self.vector_at(t)[index]

    def total(self, t: int) -> int:
        return sum(self.vector_at(t))

    def validate_recurrence(self, extra_steps: int = 32) -> bool:
        if extra_steps < 0:
            raise ValueError("extra_steps must be >= 0")

        current = self.initial_vector
        limit = self.order + extra_steps

        for t in range(limit + 1):
            if self.vector_at(t) != current:
                return False
            current = self.step_vector(current)

        return True
