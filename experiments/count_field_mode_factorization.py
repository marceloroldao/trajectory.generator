"""Factor the 8-dimensional Floquet count field into invariant modes.

We start from the exact 3-step operator F on the 16-state private space and
restrict attention to the Krylov subspace generated by the initial count
vector.  The previous experiment proved this reachable subspace has dimension
8.  Here we derive an explicit 8x8 companion representation, factor its
characteristic polynomial over Q when possible, and search for invariant
subspaces associated with rational factors.
"""
from __future__ import annotations

from fractions import Fraction

from count_vector_recurrence import mat_phase, mm, mv, vec0, minimal_vector_recurrence, rank_q


def poly_mul(a,b):
    out=[Fraction(0)]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        for j,y in enumerate(b):
            out[i+j]+=x*y
    return out


def poly_eval_matrix(coeffs,A):
    # coeffs low->high
    n=len(A)
    I=[[Fraction(int(i==j)) for j in range(n)] for i in range(n)]
    Z=[[Fraction(0) for _ in range(n)] for _ in range(n)]
    P=I
    R=[row[:] for row in Z]
    for c in coeffs:
        for i in range(n):
            for j in range(n):
                R[i][j]+=c*P[i][j]
        P=mm_frac(A,P)
    return R


def mm_frac(A,B):
    return [[sum(A[i][k]*B[k][j] for k in range(len(B))) for j in range(len(B[0]))] for i in range(len(A))]


def nullspace_q(A):
    A=[[Fraction(x) for x in row] for row in A]
    m=len(A); n=len(A[0]); r=0; piv=[]
    for c in range(n):
        p=next((i for i in range(r,m) if A[i][c]),None)
        if p is None: continue
        A[r],A[p]=A[p],A[r]
        q=A[r][c]; A[r]=[x/q for x in A[r]]
        for i in range(m):
            if i!=r and A[i][c]:
                q=A[i][c]; A[i]=[A[i][j]-q*A[r][j] for j in range(n)]
        piv.append(c); r+=1
    free=[c for c in range(n) if c not in piv]
    basis=[]
    for f in free:
        x=[Fraction(0)]*n; x[f]=1
        for i,c in reversed(list(enumerate(piv))):
            x[c]=-sum(A[i][j]*x[j] for j in free)
        basis.append(x)
    return basis


def companion_from_recurrence(coeff):
    # V_{n+d}=sum_i coeff[i] V_{n+i}; state=[V_n..V_{n+d-1}]
    d=len(coeff)
    C=[[Fraction(0)]*d for _ in range(d)]
    for i in range(d-1): C[i][i+1]=1
    for j,c in enumerate(coeff): C[d-1][j]=c
    return C


def divisors(n):
    out=[]
    for d in range(1,abs(n)+1):
        if n%d==0:
            out.extend([d,-d])
    return sorted(set(out))


def synthetic_div(poly,r):
    # poly low->high, divide by (x-r)
    hi=list(reversed(poly))
    q=[hi[0]]
    for a in hi[1:]: q.append(a+r*q[-1])
    rem=q.pop()
    return list(reversed(q)),rem


def factor_linear_integer(poly):
    p=[Fraction(x) for x in poly]
    roots=[]
    while len(p)>1 and p[0].denominator==1 and p[-1].denominator==1:
        c=int(p[0]); lc=int(p[-1])
        found=None
        for num in divisors(c if c else 1):
            for den in divisors(lc):
                if den==0: continue
                r=Fraction(num,den)
                val=sum(p[i]*(r**i) for i in range(len(p)))
                if val==0:
                    found=r; break
            if found is not None: break
        if found is None: break
        p,rem=synthetic_div(p,found); assert rem==0
        roots.append(found)
    return roots,p


def main():
    M=[mat_phase(p) for p in range(3)]
    F=mm(M[2],mm(M[1],M[0]))
    v0=vec0()
    d,coeff,krylov=minimal_vector_recurrence(F,v0)
    assert d==8
    C=companion_from_recurrence(coeff)
    # Characteristic polynomial implied by recurrence:
    # x^8 - sum_i coeff[i] x^i
    char=[-Fraction(c) for c in coeff] + [Fraction(1)]
    print('reachable_dimension',d)
    print('charpoly_low_to_high',char)
    roots,residual=factor_linear_integer(char)
    print('rational_linear_roots',roots)
    print('residual_factor_low_to_high',residual)

    # Search simple invariant kernels from the factors (x-r).
    for r in roots:
        P=poly_eval_matrix([ -r, Fraction(1)],C)
        ns=nullspace_q(P)
        print('eigenspace',r,'dimension',len(ns))

    # Search whether the residual factor splits into low-degree integer factors
    # by brute force monic quadratics/cubics with small coefficients.
    found=[]
    R=residual
    for deg in (2,3,4):
        if len(R)-1 <= deg: continue
        import itertools
        for mids in itertools.product(range(-4,5), repeat=deg):
            q=[Fraction(x) for x in mids]+[Fraction(1)]
            # polynomial long division low->high via reversed lists
            A=list(reversed(R)); B=list(reversed(q)); work=A[:]; quo=[]
            while len(work)>=len(B):
                c=work[0]/B[0]; quo.append(c)
                for j in range(len(B)): work[j]-=c*B[j]
                while work and work[0]==0: work.pop(0)
            if not work:
                found.append((q,list(reversed(quo))))
                print('small_factor',q,'cofactor',list(reversed(quo)))
                break
        if found: break

    # Numerical roots only for interpretation, never used for exact claims.
    try:
        import numpy as np
        rr=np.roots([float(x) for x in reversed(char)])
        rr=sorted(rr,key=lambda z: -abs(z))
        print('numeric_roots')
        for z in rr:
            print(complex(z), 'abs',abs(z))
    except Exception as e:
        print('numeric_roots_unavailable',repr(e))

if __name__=='__main__':
    main()
