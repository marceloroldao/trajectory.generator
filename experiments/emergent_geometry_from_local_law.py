"""Test whether the operational geometry emerges from the local law alone.

We start only from the eight public initial G-states and the local update

    G' = L(G,z) ^ N(G),   N = I(G) ^ Gch(G)

where I and Gch are the two composite nonlinear channels.  No 37-state
admissibility set and no 49-edge reference domain are consulted while growing
the candidate universe: both labels z=0,1 are applied at every reachable state.

Only after the candidate universe is generated do we compare it with the
validated 37-state/49-edge operational graph.  This distinguishes a genuine
invariant manifold generated by the law from a law that was merely fitted on
that manifold.
"""
from __future__ import annotations

from collections import deque

from nonlinear_ablation import full_graph, linear_step, summarize


def channels(g):
    g0,g1,g2,g3,g4,g5 = map(int,g)
    t0 = g1 & g4
    t1 = g1 & g5
    t2 = g0 & g3 & g5
    t3 = g1 & g4 & g5
    t4 = g2 & g4 & g5
    I = t0 ^ t1 ^ t3
    Gch = t2 ^ t4
    return I,Gch


def local_step(g,z):
    out = list(linear_step(g,z))
    I,Gch = channels(g)
    out[4] ^= I ^ Gch
    return tuple(out)


def grow(initial):
    seen=set(initial)
    q=deque(initial)
    edges={}
    while q:
        s=q.popleft()
        outs=[]
        for z in (0,1):
            d=local_step(s,z)
            outs.append((z,d))
            if d not in seen:
                seen.add(d); q.append(d)
        edges[s]=outs
    return edges,tuple(sorted(seen))


def edge_set(edges):
    return {(s,z,d) for s,outs in edges.items() for z,d in outs}


def main():
    reference,initial=full_graph()  # used only to obtain the public initial G states
    generated,nodes=grow(initial)

    ref_e=edge_set(reference); gen_e=edge_set(generated)
    ref_nodes=set(reference) | {d for outs in reference.values() for _,d in outs}
    gen_nodes=set(nodes)

    print('initial_states',len(set(initial)))
    print('generated',summarize('generated_from_local_law',generated,initial))
    print('reference',summarize('reference',reference,initial))
    print('node_agreement',len(ref_nodes & gen_nodes),'/',len(ref_nodes))
    print('generated_states',len(gen_nodes),'reference_states',len(ref_nodes),'extra_states',len(gen_nodes-ref_nodes),'missing_states',len(ref_nodes-gen_nodes))
    print('edge_agreement',len(ref_e & gen_e),'/',len(ref_e))
    print('generated_edges',len(gen_e),'reference_edges',len(ref_e),'extra_edges',len(gen_e-ref_e),'missing_edges',len(ref_e-gen_e))
    print('exact_geometry',gen_nodes==ref_nodes and gen_e==ref_e)

    # A necessary condition for spontaneous emergence of the old manifold is
    # invariance: every local-law transition from a reference state must remain
    # inside the reference node set.
    escaping=[]
    for s in sorted(ref_nodes):
        for z in (0,1):
            d=local_step(s,z)
            if d not in ref_nodes:
                escaping.append((s,z,d))
    print('reference_manifold_escape_edges',len(escaping))
    print('escape_sample',escaping[:10])


if __name__=='__main__':
    main()
